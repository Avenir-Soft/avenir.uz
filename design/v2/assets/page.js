      if (lang === 'uz') { it.n.nodeValue = raw; continue; }
      var key = norm(raw), out = tr(key);
      if (out === key) { it.n.nodeValue = raw; continue; }
      it.n.nodeValue = raw.match(/^\s*/)[0] + out + raw.match(/\s*$/)[0];
